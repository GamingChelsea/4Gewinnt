public class Player
{
    int wins;
    String name;

    Player(String name)
    {
        this.name = name;
    }

    public int getWins()
    {
        return wins;
    }
    public String getName()
    {
        return name;
    }
    public void setWins(int wins)
    {
        this.wins = wins;
    }
    public void setName(String name)
    {
        this.name = name;
    }
}
